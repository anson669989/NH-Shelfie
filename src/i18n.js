const DICTS = { 'zh-TW': zh, en, ja }
export const LANGUAGES = [
  { code: 'zh-TW', label: '繁體中文' },
  { code: 'en', label: 'English' },
  { code: 'ja', label: '日本語' },
]

function systemLang() {
  const l = (typeof navigator !== 'undefined' && navigator.language) || 'zh-TW'
  if (/^ja/i.test(l)) return 'ja'
  if (/^zh/i.test(l)) return 'zh-TW'
  return 'en'
}

export const currentLang = computed(() => (DICTS[settings.language] ? settings.language : systemLang()))

export function t(key, vars = {}) {
  const dict = DICTS[currentLang.value] || zh
  let s = dict[key] ?? zh[key] ?? key
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** 依錯誤碼取得訊息 */
export function errText(err) {
  const code = err?.code || 'UNKNOWN'
  return t(`err.${code}`, { sec: err?.retryAfter ?? 30 })
}
